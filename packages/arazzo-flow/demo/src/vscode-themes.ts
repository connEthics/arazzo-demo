export function applyVsCodeTheme(kind: keyof typeof VSCODE_THEMES | null): void {
  const body = document.body;
  body.classList.remove('vscode-light', 'vscode-dark', 'vscode-high-contrast');
  body.removeAttribute('data-vscode-theme-kind');
  for (const p of [...body.style]) if (p.startsWith('--vscode-')) body.style.removeProperty(p);
  if (!kind) return;
  body.classList.add(kind);
  body.setAttribute('data-vscode-theme-kind', kind);
  for (const [k, v] of Object.entries(VSCODE_THEMES[kind])) body.style.setProperty(`--vscode-${k}`, v);
}
