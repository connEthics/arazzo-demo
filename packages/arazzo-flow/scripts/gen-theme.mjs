/**
 * Generates src/styles/theme-connethics.css: the ConnEthics brand tokens (--ce-*) used by the
 * component, resolved to literal values and scoped to `.af-root`, so the package works without
 * the global brand stylesheet.
 *
 * Source of truth: arazzo-vscode/specs/002-arazzo-1-1-refonte/brand/tokens.css (lot B1).
 * Usage: node scripts/gen-theme.mjs <path/to/brand/tokens.css>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/gen-theme.mjs <brand/tokens.css>');
  process.exit(2);
}
const css = readFileSync(src, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

/** Top-level rules (selector → declarations), @media blocks skipped. */
function rules(text) {
  const out = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const selector = text.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < text.length && depth) {
      if (text[j] === '{') depth++;
      else if (text[j] === '}') depth--;
      j++;
    }
    if (!selector.startsWith('@')) out.push({ selector, body: text.slice(open + 1, j - 1) });
    i = j;
  }
  return out;
}
function decls(body) {
  const m = new Map();
  for (const d of body.split(';')) {
    const k = d.indexOf(':');
    if (k < 0) continue;
    const name = d.slice(0, k).trim();
    if (name.startsWith('--ce-')) m.set(name, d.slice(k + 1).trim());
  }
  return m;
}

const all = rules(css);
const prim = decls(all.find((r) => r.selector === ':root').body);
const light = decls(all.find((r) => r.selector.startsWith(':root,') && r.selector.includes('[data-theme="light"]')).body);
const dark = decls(all.find((r) => r.selector.startsWith('[data-theme="dark"]')).body);

function resolve(value, theme, seen = new Set()) {
  return value.replace(/var\((--ce-[a-z0-9-]+)\s*(?:,\s*([^()]*(?:\([^()]*\))*[^()]*))?\)/g, (_, name, fb) => {
    if (seen.has(name)) throw new Error(`cycle on ${name}`);
    const v = theme.get(name) ?? prim.get(name);
    if (v === undefined) {
      if (fb !== undefined) return fb.trim();
      throw new Error(`unknown token ${name}`);
    }
    return resolve(v, theme, new Set([...seen, name]));
  });
}

// Tokens referenced by the component stylesheets.
const used = new Set();
for (const f of ['arazzo-flow.css', 'theme-vscode.css']) {
  const text = readFileSync(join(here, '..', 'src', 'styles', f), 'utf8');
  for (const m of text.matchAll(/var\((--ce-[a-z0-9-]+)/g)) used.add(m[1]);
}
const names = [...used].sort();
const block = (theme) => names.map((n) => `  ${n}: ${resolve(theme.get(n) ?? prim.get(n) ?? (() => { throw new Error(`missing ${n}`); })(), theme)};`).join('\n');

const hash = createHash('sha256').update(readFileSync(src)).digest('hex').slice(0, 12);
const out = `/*
 * GENERATED by scripts/gen-theme.mjs from brand/tokens.css (sha256 ${hash}…) — do not edit.
 * ConnEthics tokens (--ce-*) used by @connethics/arazzo-flow, resolved and scoped to .af-root:
 *   - default and data-af-theme="connethics-light": light palette;
 *   - data-af-theme="connethics-dark": dark palette;
 *   - data-af-theme="auto": [data-theme] on an ancestor, else prefers-color-scheme;
 *   - data-af-theme="vscode": these values are only fallbacks of the --vscode-* mapping (theme-vscode.css).
 */
.af-root {
  color-scheme: light;
${block(light)}
}

.af-root[data-af-theme='connethics-dark'],
.af-root[data-af-theme='vscode'][data-af-dark] {
  color-scheme: dark;
${block(dark)}
}

@media (prefers-color-scheme: dark) {
  .af-root[data-af-theme='auto'] {
    color-scheme: dark;
${block(dark).replace(/^ {2}/gm, '    ')}
  }
}

:where([data-theme='light']) .af-root[data-af-theme='auto'] {
  color-scheme: light;
${block(light)}
}

:where([data-theme='dark']) .af-root[data-af-theme='auto'] {
  color-scheme: dark;
${block(dark)}
}
`;
writeFileSync(join(here, '..', 'src', 'styles', 'theme-connethics.css'), out);
console.log(`theme-connethics.css: ${names.length} tokens × 2 palettes`);
